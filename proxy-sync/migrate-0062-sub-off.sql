-- 8.31（カジの依頼3）リストから外れた商品のカードを「受付終了」にする
--
-- MW が欠品した・販売終了した・上限を0にした商品は、配信の対象から
-- 外れる（mw_sub の条件に合わなくなる）。でも**前に出したカード**は
-- Discord に残ったままで、会員が買えない商品を見てしまっていた。
--
-- この migrate で足す列
--   sub_post.off_at … そのカードを「この商品の受付は終わりました」に
--                     書き換えた日時。入っている行は二度書き換えない。
--                     ⚙「受付終了から◯日で消す」（既定 0＝消さない）が
--                     入っていれば、この時刻から数えて消す。
--
-- カードは**消さずに残す**のが既定（会員が見た覚えのある投稿が
-- 急に消えると不安になるため）。消すのは⚙で選んだときだけ。

ALTER TABLE sub_post ADD COLUMN off_at TEXT;
