-- 7.134（【T】の直し）在庫の記録の「基準」を控える列
--
-- これまで mw_move・mw_stat は「掲載数が変わった回だけ」書いていたので、
-- 商品ごとの**基準**（はじめて見た日と、そのときの数）がどこにも残らず、
-- その商品の**最初の変化が「初回の記録」**になっていた。
-- 記録のある日数が 0日（＝1日として扱う）なので、その1回の減りが
-- そのまま「20点/日」になり、「欠品までの見込み 1日」「記録 1日分」と出ていた。
--
-- base_qty … 基準の数（はじめて記録したときの掲載数。(JAN,社) ごとの合計）
--             初回は出来事として数えず、この数だけを控える。

ALTER TABLE mw_stat ADD COLUMN base_qty INTEGER;
